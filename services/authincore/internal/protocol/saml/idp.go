package saml

// SAML Identity Provider (IdP) implementation.
//
// AuthinCore acts as the IdP when enterprise apps (Salesforce, Jira, Slack…)
// point their SAML SP metadata at us. Flow:
//
//  1. External SP redirects browser to POST/Redirect /saml/idp/{org_id}/sso
//     with an encoded AuthnRequest.
//  2. IdP.SingleSignOn validates the request, checks the SP is registered,
//     and redirects the browser to the self-service login UI if no session exists.
//  3. After login the flow engine calls IdP.IssueAssertion which:
//     - builds a signed SAMLResponse with an Assertion
//     - POSTs it to the SP's ACS URL (POST binding)
//  4. IdP.Metadata serves the IdP EntityDescriptor XML for SP admins to paste.

